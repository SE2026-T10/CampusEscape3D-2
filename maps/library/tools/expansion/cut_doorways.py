#!/usr/bin/env python3
"""Expanded Library expansion, Phase 2: cut the three approved doorways into the
existing scene, maps/library/scenes/expanded_library.tscn, as a minimal text patch.

The level was generated by maps/library/tools/build_expanded_graybox.gd, which is
frozen (a rebuild would revert the door-frame fix and drop the Expansion
sub-scene), so its walls are edited here instead, touching only:
  - the collision box of each cut wall: shortened to one side of the doorway,
    plus a new body for the other side and a header body above the doorway
    (2.6 m, the level's door height), in the same parent;
  - batched decoration boxes (BatchedBoxes `boxes`) that cross the doorway:
    split around it, keeping the part above the door height (the header's
    plaster) - nothing else in the scene changes;
  - the NavigationRegion3D joins the group the navmesh is baked from, so the
    Expansion sub-scene's geometry is baked into the same navmesh.
Approved by the owner (expansion Phase 2): cut 1 = B west wall at z -9 (main
stacks cross aisle -> west service stair), cut 2 = D east wall at z -23 (book
processing -> electrical room, a staff-card door), cut 3 = B/C wall at z -21
(main stacks -> Study 1).

Usage (from the project folder):  python3 maps/library/tools/expansion/cut_doorways.py [--dry-run]
Idempotent: it refuses to run twice (the new nodes would already exist).
"""
import re, sys, random

SCENE = "maps/library/scenes/expanded_library.tscn"
NAV_GROUP = "expanded_navigation_source"
DOOR_TOP = 2.6
WALL_T = 0.3
WALL_H = 4.2
# name, wall node, wall x, the wall's full z extent [lo, hi], door z range, header node name
CUTS = [
    ("cut 1 (B west wall)", "NavigationRegion3D/Ground/B_MainStacks/Wall05_0", -36.0, (-28.15, 28.15), (-10.0, -8.0), "Header_WestServiceDoor"),
    ("cut 2 (D east wall)", "NavigationRegion3D/Ground/D_ServiceCorridor/Wall06_0", 36.0, (-28.15, 22.5), (-24.0, -22.0), "Header_ElectricalRoomDoor"),
    ("cut 3 (B/C wall)", "NavigationRegion3D/Ground/B_MainStacks/Wall07_0", -12.0, (-28.15, -3.5), (-22.0, -20.0), "Header_Study1StacksDoor"),
]
NUM = r"-?\d+(?:\.\d+)?(?:e-?\d+)?"


def fmt(x):
    s = ("%.6f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def shape_id(size):
    return "BoxShape_" + "_".join(("%.3f" % v).replace(".", "p") for v in size)


def parse_nodes(lines):
    """[(start, end, name, parent_path, header)] for every [node ...] block."""
    nodes = []
    starts = [i for i, l in enumerate(lines) if l.startswith("[node ")]
    for k, i in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else len(lines)
        h = lines[i]
        name = re.search(r'name="([^"]*)"', h).group(1)
        m = re.search(r'parent="([^"]*)"', h)
        parent = m.group(1) if m else None
        nodes.append((i, end, name, parent, h))
    return nodes


def path_of(name, parent):
    if parent is None:
        return "."
    return name if parent == "." else parent + "/" + name


def node_transform(lines, start, end):
    for j in range(start + 1, end):
        m = re.match(r"transform = Transform3D\(([^)]*)\)", lines[j])
        if m:
            v = [float(x) for x in m.group(1).split(",")]
            return v  # basis x(3) y(3) z(3) origin(3) (Godot writes the basis columns' components row by row)
        if lines[j].startswith("position = Vector3("):
            o = [float(x) for x in re.search(r"Vector3\(([^)]*)\)", lines[j]).group(1).split(",")]
            return [1, 0, 0, 0, 1, 0, 0, 0, 1] + o
    return [1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0]


def is_translation(t):
    return all(abs(a - b) < 1e-6 for a, b in zip(t[:9], [1, 0, 0, 0, 1, 0, 0, 0, 1]))


def main():
    dry = "--dry-run" in sys.argv
    text = open(SCENE, encoding="utf-8").read()
    if "Header_WestServiceDoor" in text:
        sys.exit("Already applied (Header_WestServiceDoor exists).")
    lines = text.split("\n")
    nodes = parse_nodes(lines)
    by_path = {path_of(n[2], n[3]): n for n in nodes}
    transforms = {p: node_transform(lines, n[0], n[1]) for p, n in by_path.items()}

    def global_origin(path):
        o = [0.0, 0.0, 0.0]
        p = path
        while p and p != ".":
            t = transforms.get(p)
            if t is None or not is_translation(t):
                raise SystemExit("Unexpected rotated or missing ancestor: " + p)
            o = [o[0] + t[9], o[1] + t[10], o[2] + t[11]]
            p = p.rsplit("/", 1)[0] if "/" in p else "."
        return o

    report = []
    edits = {}        # line index -> replacement text
    new_shapes = {}   # id -> size
    rng = random.Random(20261015)
    used_ids = set(re.findall(r"unique_id=(\d+)", text))

    def new_uid():
        while True:
            u = str(rng.randint(10**8, 2**31 - 1))
            if u not in used_ids:
                used_ids.add(u)
                return u

    inserts = {}      # line index -> text inserted after that node block
    for label, wall_path, x, (lo, hi), (d0, d1), header in CUTS:
        n = by_path[wall_path]
        t = transforms[wall_path]
        assert is_translation(t) and abs(t[9] - x) < 1e-6, (label, t)
        assert abs((t[11] - (lo + hi) / 2)) < 1e-3, (label, "unexpected wall centre", t[11])
        shape_line = next(j for j in range(n[0], n[1] + 6) if lines[j].startswith("shape = SubResource") and "BoxShape_0p300_4p200" in lines[j])
        a_len, b_len = d0 - lo, hi - d1
        a_size, b_size, h_size = (WALL_T, WALL_H, a_len), (WALL_T, WALL_H, b_len), (WALL_T, WALL_H - DOOR_TOP, d1 - d0)
        for s in (a_size, b_size, h_size):
            new_shapes[shape_id(s)] = s
        # The existing body keeps its name and becomes the lo side of the doorway.
        tr_line = next(j for j in range(n[0], n[1]) if lines[j].startswith("transform = "))
        edits[tr_line] = "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %s, 2.1, %s)" % (fmt(x), fmt((lo + d0) / 2))
        edits[shape_line] = 'shape = SubResource("%s")' % shape_id(a_size)
        parent = n[3]
        name = n[2]
        block = []
        for node_name, centre_z, cy, size in [(name + "_cut", (d1 + hi) / 2, 2.1, b_size), (header, (d0 + d1) / 2, DOOR_TOP + (WALL_H - DOOR_TOP) / 2, h_size)]:
            block += ['[node name="%s" type="StaticBody3D" parent="%s" unique_id=%s]' % (node_name, parent, new_uid()),
                      "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %s, %s, %s)" % (fmt(x), fmt(cy), fmt(centre_z)),
                      "collision_mask = 0", "",
                      '[node name="Shape" type="CollisionShape3D" parent="%s/%s" unique_id=%s]' % (parent, node_name, new_uid()),
                      'shape = SubResource("%s")' % shape_id(size), ""]
        # after the wall's own block (its Shape child follows it)
        shape_node = by_path[wall_path + "/Shape"]
        inserts[shape_node[1]] = inserts.get(shape_node[1], []) + block
        report.append("%s: %s -> z [%.2f, %.2f] + %s_cut z [%.2f, %.2f] + %s above %.1f m" % (label, name, lo, d0, name, d1, hi, header, DOOR_TOP))

    # Decoration boxes crossing a doorway.
    box_changes = 0
    skipped = []
    for p, n in by_path.items():
        for j in range(n[0], n[1]):
            if not lines[j].startswith("boxes = PackedFloat32Array("):
                continue
            tokens = [v.strip() for v in lines[j][len("boxes = PackedFloat32Array("):-1].split(",")]
            vals = [float(v) for v in tokens]
            assert len(vals) % 16 == 0 and lines[j].endswith(")")
            try:
                g = global_origin(p)
            except SystemExit:
                # Under a rotated parent (the stair ramps): none of these is near a doorway.
                t = [transforms.get(q) for q in [p.rsplit("/", k)[0] for k in range(p.count("/") + 1)]]
                skipped.append(p)
                continue
            out, changed = [], False
            for b in range(0, len(vals), 16):
                e = vals[b:b + 16]
                diag = abs(e[1]) + abs(e[2]) + abs(e[3]) + abs(e[5]) + abs(e[6]) + abs(e[7]) < 1e-6
                sx, sy, sz = abs(e[0]), abs(e[4]), abs(e[8])
                cx, cy, cz = e[9] + g[0], e[10] + g[1], e[11] + g[2]
                hit = None
                for label, _, x, _, (d0, d1), _ in CUTS:
                    if abs(cx - x) - sx / 2 < 0.5 and cz + sz / 2 > d0 + 1e-4 and cz - sz / 2 < d1 - 1e-4 and cy - sy / 2 < DOOR_TOP - 1e-4 and cy + sy / 2 > 0.02:
                        hit = (label, d0, d1)
                if hit is None:
                    out.append(tokens[b:b + 16])   # untouched: the original numbers, as written
                    continue
                if not diag:
                    raise SystemExit("A rotated decoration box crosses %s in %s: handle it by hand." % (hit[0], p))
                label, d0, d1 = hit
                z0, z1, y0, y1 = cz - sz / 2, cz + sz / 2, cy - sy / 2, cy + sy / 2
                pieces = []
                if z0 < d0 - 1e-4:
                    pieces.append((z0, d0, y0, y1))
                if z1 > d1 + 1e-4:
                    pieces.append((d1, z1, y0, y1))
                if y1 > DOOR_TOP + 1e-4:
                    pieces.append((max(z0, d0), min(z1, d1), DOOR_TOP, y1))
                for (pz0, pz1, py0, py1) in pieces:
                    f = list(e)
                    f[8] = pz1 - pz0
                    f[4] = py1 - py0
                    f[11] = (pz0 + pz1) / 2 - g[2]
                    f[10] = (py0 + py1) / 2 - g[1]
                    out.append([fmt(v) for v in f])
                changed = True
                box_changes += 1
                report.append("  decoration %s: box at (%.2f, %.2f, %.2f) size (%.2f, %.2f, %.2f) -> %d piece(s) [%s]" % (p.split("/")[-1], cx, cy, cz, sx, sy, sz, len(pieces), label))
            if changed:
                edits[j] = "boxes = PackedFloat32Array(" + ", ".join(v for e in out for v in e) + ")"

    # Other dressing near the doorways (reported; nothing else is expected).
    for p, n in by_path.items():
        if not p.startswith("Dressing/") or any(lines[j].startswith("boxes =") for j in range(n[0], n[1])):
            continue
        try:
            g = global_origin(p)
        except SystemExit:
            continue
        for label, _, x, _, (d0, d1), _ in CUTS:
            if abs(g[0] - x) < 1.0 and d0 - 1.0 < g[2] < d1 + 1.0 and g[1] < 3.0:
                report.append("  NOTE: dressing node %s at %s is near %s" % (p, g, label))

    # The navigation region joins the bake group.
    nav = by_path["NavigationRegion3D"]
    if "groups=" in lines[nav[0]]:
        raise SystemExit("NavigationRegion3D already has groups.")
    edits[nav[0]] = lines[nav[0]][:-1] + ' groups=["%s"]]' % NAV_GROUP

    # Write.
    first_node = nodes[0][0]
    existing = set(re.findall(r'sub_resource type="BoxShape3D" id="([^"]+)"', text))
    shape_lines = []
    for sid, size in new_shapes.items():
        if sid in existing:
            continue
        shape_lines += ['[sub_resource type="BoxShape3D" id="%s"]' % sid, "size = Vector3(%s)" % ", ".join(fmt(v) for v in size), ""]
    # Shapes no longer used by any node (the cut walls' old full-length boxes) are dropped.
    replaced = set(re.search(r'SubResource\("([^"]+)"\)', lines[j]).group(1) for j in edits if lines[j].startswith("shape = "))
    still_used = set(re.findall(r'SubResource\("([^"]+)"\)', "\n".join(edits.get(i, l) for i, l in enumerate(lines))))
    drop = set()
    for i, l in enumerate(lines):
        m = re.match(r'\[sub_resource type="BoxShape3D" id="([^"]+)"\]', l)
        if m and m.group(1) in replaced and m.group(1) not in still_used:
            drop.update({i, i + 1, i + 2})
            report.append("unused shape removed: " + m.group(1))
    result = []
    for i, l in enumerate(lines):
        if i in drop:
            continue
        if i == first_node:
            result += shape_lines
        if i in inserts:
            result += inserts[i]
        result.append(edits.get(i, l))
    print("\n".join(report))
    print("batched nodes under rotated parents, skipped (stairs): %d" % len(skipped))
    for q in skipped:
        assert "/Stairs/" in q, q
    print("%d decoration boxes split; %d new shape resources; NavigationRegion3D in group %s" % (box_changes, len([1 for s in new_shapes if s not in existing]), NAV_GROUP))
    if not dry:
        open(SCENE, "w", encoding="utf-8").write("\n".join(result))
        print("Written", SCENE)


if __name__ == "__main__":
    main()
